// Generates a migration with the feeds of profiles of config/pdf.json (one feed per PDF file).
// Usage: node dist/scripts/gen-pdf-feeds-sql.js <YYYYMMDDHHMMSS_name.sql> <profile>[,<profile>...] [--ref-check]
// --ref-check also writes the check on pdf refs; only the first PDF migration needs it.
import { realpathSync } from 'node:fs';
import { rename, rm, writeFile } from 'node:fs/promises';
import { basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadCampus } from '../src/campus.js';
import { buildingKey } from '../src/domain/building.js';
import { loadPdfConfig, PdfConfigError } from '../src/sources/pdf/config.js';
import { PROFILES } from '../src/sources/pdf/profiles.js';
import type { ParsedProfile } from '../src/sources/pdf/runner.js';

function sql(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

// added_at comes from the migration timestamp, so the output depends only on the configuration and the name.
export function addedAtOf(file: string): string {
  const m = /^(\d{4})(\d{2})(\d{2})(\d{2})(\d{2})(\d{2})_[a-z0-9_]{1,60}\.sql$/.exec(basename(file));
  if (!m) throw new PdfConfigError('usage');
  return `timestamptz '${m[1]}-${m[2]}-${m[3]} ${m[4]}:${m[5]}:${m[6]}+00'`;
}

const REF_CHECK = [
  "-- A pdf ref is <profile>:<key> (for example discag:0881); a canonical unical.it URL stays accepted.",
  'alter table aule.calendars drop constraint calendars_url_ref;',
  "alter table aule.calendars add constraint calendars_url_ref check (source <> 'dimes' or aule.source_url_ok(ref));",
  'alter table aule.calendars add constraint calendars_pdf_ref',
  "  check (source <> 'pdf' or aule.source_url_ok(ref) or ref ~ '^[a-z]{2,10}:[A-Za-z0-9_-]{1,60}$');",
];

export function renderPdfFeeds(profiles: readonly ParsedProfile[], options: { addedAt: string; refCheck: boolean }): string {
  const rows = profiles
    .flatMap((p) => p.feeds)
    .map((f, i) => `  (${sql(f.id)}, 'pdf', ${sql(f.ref)}, ${sql(f.label)}, true, ${options.addedAt} + ${i} * interval '1 millisecond')`);
  const names = `profile${profiles.length > 1 ? 's' : ''} ${profiles.map((p) => p.key).join(', ')}`;
  return [
    `-- Generated by scripts/gen-pdf-feeds-sql.ts from config/pdf.json (${names}${options.refCheck ? ', --ref-check' : ''}). Do not edit: write a new migration with the generator instead.`,
    ...(options.refCheck ? REF_CHECK : []),
    '-- Timetables published as PDF files: one feed per file, the id is the synthetic id of pdf and the ref.',
    'insert into aule.calendars (id, source, ref, label, active, added_at) values',
    rows.join(',\n'),
    'on conflict do nothing;',
    '',
  ].join('\n');
}

// Every configured room must sit in a building of the campus map, or it would never be drawn.
export function checkBuildings(profile: ParsedProfile, campusKeys: ReadonlySet<string>): void {
  for (const building of profile.buildings) {
    const key = buildingKey(building);
    if (!key || !campusKeys.has(key)) throw new PdfConfigError('room_building');
  }
}

const ROOT = new URL('../../', import.meta.url);

async function main(argv: string[]): Promise<void> {
  const [out, key, ...rest] = argv;
  const flags = new Set(rest);
  if (!out || !key || out.length > 500 || rest.length > 1 || (rest.length === 1 && !flags.has('--ref-check'))) {
    throw new PdfConfigError('usage');
  }
  const addedAt = addedAtOf(out);
  const keys = key.split(',');
  if (keys.length > 10 || new Set(keys).size !== keys.length) throw new PdfConfigError('usage');
  const all = await loadPdfConfig(PROFILES);
  const profiles = keys.map((k) => {
    const profile = all.find((p) => p.key === k);
    if (!profile) throw new PdfConfigError('usage');
    return profile;
  });
  const campus = await loadCampus(fileURLToPath(new URL('public/data/campus.geojson', ROOT))).catch(() => {
    throw new PdfConfigError('campus');
  });
  for (const profile of profiles) checkBuildings(profile, campus.keys);
  const tmp = `${out}.tmp-${process.pid}`;
  try {
    await writeFile(tmp, renderPdfFeeds(profiles, { addedAt, refCheck: flags.has('--ref-check') }), { encoding: 'utf8', flag: 'wx' });
    await rename(tmp, out);
  } catch {
    await rm(tmp, { force: true });
    throw new PdfConfigError('out_file');
  }
  const count = profiles.reduce((n, p) => n + p.feeds.length, 0);
  console.log(`pdf feeds written: ${count} feeds of ${keys.join(', ')}`);
}

// Compares real paths: started through a symbolic link, the generator must still run and never exit 0 doing nothing.
function runDirectly(): boolean {
  const script = process.argv[1];
  if (!script) return false;
  try {
    return realpathSync(script) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (runDirectly()) {
  main(process.argv.slice(2)).catch((err: unknown) => {
    process.stderr.write(`${err instanceof PdfConfigError ? err.field : 'unexpected'}\n`);
    process.exitCode = 1;
  });
}
