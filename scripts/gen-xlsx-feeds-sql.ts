// Generates the migration with the DIAm xlsx feeds, one per sheet of config/diam.json.
// Usage: node dist/scripts/gen-xlsx-feeds-sql.js <out.sql>
import { realpathSync } from 'node:fs';
import { rename, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { loadCampus } from '../src/campus.js';
import { buildingKey } from '../src/domain/building.js';
import { DiamConfigError, loadDiamConfig, type DiamConfig } from '../src/sources/xlsx/config.js';

const ADDED_AT = "timestamptz '2026-11-10 09:05:00+00'";

function sql(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

export function renderXlsxFeeds(config: DiamConfig): string {
  const rows = config.sheets.map(
    (s, i) => `  (${sql(s.id)}, 'xlsx', ${sql(s.ref)}, ${sql(s.label)}, true, ${ADDED_AT} + ${i} * interval '1 millisecond')`,
  );
  return [
    '-- Generated by scripts/gen-xlsx-feeds-sql.ts from config/diam.json. Do not edit: write a new migration with the generator instead.',
    '-- DIAm timetables published as xlsx files: one feed per sheet, the id is the synthetic id of xlsx and the ref.',
    'insert into aule.calendars (id, source, ref, label, active, added_at) values',
    rows.join(',\n'),
    'on conflict do nothing;',
    '',
  ].join('\n');
}

// Every configured room must sit in a building of the campus map, or it would never be drawn.
export function checkBuildings(config: DiamConfig, campusKeys: ReadonlySet<string>): void {
  for (const room of config.rooms.values()) {
    const key = buildingKey(room.building);
    if (!key || !campusKeys.has(key)) throw new DiamConfigError('room_building');
  }
}

const ROOT = new URL('../../', import.meta.url);

async function main(argv: string[]): Promise<void> {
  const [out, ...rest] = argv;
  if (!out || rest.length > 0 || out.length > 500 || !out.endsWith('.sql')) throw new DiamConfigError('usage');
  const config = await loadDiamConfig();
  const campus = await loadCampus(fileURLToPath(new URL('public/data/campus.geojson', ROOT))).catch(() => {
    throw new DiamConfigError('campus');
  });
  checkBuildings(config, campus.keys);
  const tmp = `${out}.tmp-${process.pid}`;
  try {
    await writeFile(tmp, renderXlsxFeeds(config), { encoding: 'utf8', flag: 'wx' });
    await rename(tmp, out);
  } catch {
    await rm(tmp, { force: true });
    throw new DiamConfigError('out_file');
  }
  console.log(`xlsx feeds written: ${config.sheets.length} sheets`);
}

// Compares real paths: started through a symbolic link, the generator must still run and never exit 0 doing nothing.
function runDirectly(): boolean {
  const script = process.argv[1];
  if (!script) return false;
  try {
    return realpathSync(script) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (runDirectly()) {
  main(process.argv.slice(2)).catch((err: unknown) => {
    process.stderr.write(`${err instanceof DiamConfigError ? err.field : 'unexpected'}\n`);
    process.exitCode = 1;
  });
}
