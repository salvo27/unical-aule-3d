// Generates the migration with the DIMES feed from config/dimes.json.
// Usage: node dist/scripts/gen-dimes-feeds-sql.js <out.sql>
import { realpathSync } from 'node:fs';
import { rename, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { loadCampus } from '../src/campus.js';
import { buildingKey } from '../src/domain/building.js';
import { DimesConfigError, loadDimesConfig, type DimesConfig } from '../src/sources/dimes/config.js';

const ADDED_AT = "timestamptz '2026-11-10 09:08:00+00'";

function sql(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

export function renderDimesFeeds(config: DimesConfig): string {
  return [
    '-- Generated by scripts/gen-dimes-feeds-sql.ts from config/dimes.json. Do not edit: write a new migration with the generator instead.',
    '-- DIMES timetable app: one feed, the id is the synthetic id of dimes and the app URL.',
    'insert into aule.calendars (id, source, ref, label, active, added_at) values',
    `  (${sql(config.feedId)}, 'dimes', ${sql(config.url)}, ${sql(config.label)}, true, ${ADDED_AT})`,
    'on conflict do nothing;',
    '',
  ].join('\n');
}

// Every configured room must sit in a building of the campus map, or in one listed with the link the owner adds.
export function checkBuildings(config: DimesConfig, campusKeys: ReadonlySet<string>): void {
  for (const [building, key] of config.offMapBuildings) {
    if (!campusKeys.has(key) || campusKeys.has(buildingKey(building) ?? '')) throw new DimesConfigError('off_map_buildings');
  }
  for (const room of [...config.rooms.values(), ...config.externalRooms.values()]) {
    const key = buildingKey(room.building);
    if (!key || !(campusKeys.has(key) || config.offMapBuildings.has(room.building))) throw new DimesConfigError('room_building');
  }
}

const ROOT = new URL('../../', import.meta.url);

async function main(argv: string[]): Promise<void> {
  const [out, ...rest] = argv;
  if (!out || rest.length > 0 || out.length > 500 || !out.endsWith('.sql')) throw new DimesConfigError('usage');
  const config = await loadDimesConfig();
  const campus = await loadCampus(fileURLToPath(new URL('public/data/campus.geojson', ROOT))).catch(() => {
    throw new DimesConfigError('campus');
  });
  checkBuildings(config, campus.keys);
  const tmp = `${out}.tmp-${process.pid}`;
  try {
    await writeFile(tmp, renderDimesFeeds(config), { encoding: 'utf8', flag: 'wx' });
    await rename(tmp, out);
  } catch {
    await rm(tmp, { force: true });
    throw new DimesConfigError('out_file');
  }
  console.log('dimes feeds written: 1 feed');
}

// Compares real paths: started through a symbolic link, the generator must still run and never exit 0 doing nothing.
function runDirectly(): boolean {
  const script = process.argv[1];
  if (!script) return false;
  try {
    return realpathSync(script) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (runDirectly()) {
  main(process.argv.slice(2)).catch((err: unknown) => {
    process.stderr.write(`${err instanceof DimesConfigError ? err.field : 'unexpected'}\n`);
    process.exitCode = 1;
  });
}
